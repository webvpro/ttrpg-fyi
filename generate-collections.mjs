import fs from 'fs';
import path from 'path';

// --- Configuration ---
const SYSTEM_KEY = 'CSRD'; // The main system directory (e.g., CSRD, D&D)
const CONTENT_BASE_PATH = 'src/content/compendiums';
const CONFIG_OUTPUT_PATH = 'src/content/config.ts';
// --- End Configuration ---

/**
 * Sanitizes a directory name to be a valid JavaScript variable name.
 * Example: "Creatures-NPCs" -> "creaturesnpcs"
 * @param {string} name - The original directory name.
 * @returns {string} The sanitized name.
 */
function sanitizeName(name) {
  return name.toLowerCase().replace(/[^a-z0-9]/g, '');
}

/**
 * Generates the TypeScript code for the Astro content config file.
 * @param {string} lang - The language code (e.g., 'en').
 * @param {string[]} collectionDirs - An array of collection directory names.
 * @returns {string} The complete TypeScript file content as a string.
 */
function generateConfigFileContent(lang, collectionDirs) {
  const collectionDefinitions = collectionDirs.map(dir => {
    const varName = sanitizeName(dir);
    const collectionPath = `${CONTENT_BASE_PATH}/${SYSTEM_KEY}/${lang}/${dir}`;
    return `
// Collection for: ${dir}
const ${varName} = defineCollection({
  loader: glob({ pattern: '**/[^_]*', base: './${collectionPath}' }),
  schema: baseSchema,
});`;
  }).join('');

  const exportedCollections = collectionDirs.map(dir => `  ${sanitizeName(dir)},`).join('\n');

  return `// This file is auto-generated by the 'generate-collections.mjs' script. Do not edit manually.
// Generated on: ${new Date().toISOString()}

import { defineCollection, z } from "astro:content";
import { glob } from "astro/loaders";

// A generic base schema that allows for common fields and any other fields.
// This provides flexibility while ensuring core fields like 'title' are present.
const baseSchema = z.object({
    title: z.string(),
    aliases: z.array(z.string()).optional(),
    tags: z.array(z.string()).optional(),
    collection: z.string().optional(),
    kind: z.string().optional(),
  }).passthrough(); // .passthrough() allows any other fields without validation.

${collectionDefinitions}

// Export all the generated collections for Astro.
export const collections = {
${exportedCollections}
};
`;
}

/**
 * Main function to run the script.
 */
function main() {
  // Get language from command-line argument, default to 'en'.
  const lang = process.argv[2] || 'en';
  console.log(`Generating collections for language: "${lang}"...`);

  const systemLangPath = path.join(process.cwd(), CONTENT_BASE_PATH, SYSTEM_KEY, lang);

  if (!fs.existsSync(systemLangPath)) {
    console.error(`Error: Directory not found at "${systemLangPath}".`);
    console.error(`Please make sure the language directory exists for the system "${SYSTEM_KEY}".`);
    process.exit(1);
  }

  // Read all subdirectories to use as collection names.
  const collectionDirs = fs.readdirSync(systemLangPath, { withFileTypes: true })
    .filter(dirent => dirent.isDirectory())
    .map(dirent => dirent.name);

  if (collectionDirs.length === 0) {
    console.warn(`Warning: No collection directories found in "${systemLangPath}".`);
    return;
  }

  console.log('Found collections:', collectionDirs.join(', '));

  // Generate the file content.
  const fileContent = generateConfigFileContent(lang, collectionDirs);

  // Write the content to the config file.
  fs.writeFileSync(CONFIG_OUTPUT_PATH, fileContent, 'utf8');

  console.log(`✅ Successfully generated Astro config at "${CONFIG_OUTPUT_PATH}"!`);
}

// Run the script.
main();