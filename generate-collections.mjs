import fs from 'fs';
import path from 'path';

const OUTPUT_FILE = './src/content/cs-collection-config.ts';
const CONTENT_DIR = 'src/content/compendiums/csrd/en';

/**
 * Generates the TypeScript code for the Astro content config file.
 * @param {string} lang - The language code (e.g., 'en').
 * @param {string[]} collectionDirs - An array of collection directory names.
 * @returns {string} The complete TypeScript file content as a string.
 */
function generateConfigFileContent(collectionDirs) {
  const imports = `import { glob } from 'astro/loaders';
import { defineCollection, z } from "astro:content";

// This file is auto-generated by the 'generate-collections.mjs' script. Do not edit manually.
// Generated on: ${new Date().toISOString()}

// A generic base schema that allows for common fields and any other fields.
// This provides flexibility while ensuring core fields like 'title' are present.
const baseSchema = z.object({
    title: z.string(),
    aliases: z.array(z.string()).optional(),
    tags: z.array(z.string()).optional(),
    collection: z.string().optional(),
    kind: z.string().optional(),
  }).passthrough(); // .passthrough() allows any other fields without validation.

`;

  const collections = collectionDirs.map(dir => {
    const varName = dir.toLowerCase().replace(/[^a-z0-9]/g, '');
    return `// Collection for: ${dir}
const ${varName} = defineCollection({
  schema: baseSchema,
  loader: glob({
    pattern: '**/*.{md,mdx}',
    base: '${CONTENT_DIR}/${dir}',
  })
});`;
  }).join('\n');

  const exports = `\n// Export all the generated collections for Astro.
export const collections = {
  ${collectionDirs.map(dir => dir.toLowerCase().replace(/[^a-z0-9]/g, '')).join(',\n  ')},
};
`;

  return `${imports}\n${collections}\n${exports}\n`;
}

/**
 * Main function to run the script.
 */
function generateCollections() {
  // Get all directories from the content path
  const dirs = fs.readdirSync(CONTENT_DIR, { withFileTypes: true })
    .filter(dirent => dirent.isDirectory())
    .map(dirent => dirent.name);

  const configContent = generateConfigFileContent(dirs);

  // Write the configuration file
  fs.writeFileSync(OUTPUT_FILE, configContent);
  console.log(`Generated collection config at: ${OUTPUT_FILE}`);
  console.log(`Created ${dirs.length} collection definitions`);
}

// Run the generator
generateCollections();